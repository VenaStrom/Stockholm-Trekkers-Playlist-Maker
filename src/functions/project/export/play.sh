wait_until() {
  local time_string="$1" # e.g. "10:10"
  local target_time
  if [[ "$time_string" =~ ^([0-9]{1,2}):([0-9]{2})$ ]]; then
    local hour="${BASH_REMATCH[1]}"
    local minute="${BASH_REMATCH[2]}"
    target_time=$(date -d "today $hour:$minute" +%s)
    local now
    while true; do
      now=$(date +%s)
      if ((now >= target_time)); then
        print "Reached target time $time_string. Continuing...\n"
        break
      fi
      sleep 1
    done
  else
    print "$YELLOW" "Warning: Invalid time format '$time_string'. Expected HH:MM. Continuing without waiting.\n"
  fi
}

